/**
 * Single source of truth: accounting-game/VERSION
 * Syncs into package.json, windows/package.json, tauri.conf.json, and src/content/version.ts
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const versionFile = path.join(root, "VERSION");

function readVersion() {
  const raw = fs.readFileSync(versionFile, "utf8").trim();
  if (!/^\d+\.\d+\.\d+$/.test(raw)) {
    throw new Error(`VERSION must be semver X.Y.Z, got: ${raw}`);
  }
  return raw;
}

function patchJson(filePath, mutator) {
  const json = JSON.parse(fs.readFileSync(filePath, "utf8"));
  mutator(json);
  fs.writeFileSync(filePath, `${JSON.stringify(json, null, 2)}\n`);
}

function sync(version = readVersion()) {
  patchJson(path.join(root, "package.json"), (j) => {
    j.version = version;
  });
  patchJson(path.join(root, "windows", "package.json"), (j) => {
    j.version = version;
  });
  const tauriPath = path.join(root, "src-tauri", "tauri.conf.json");
  if (fs.existsSync(tauriPath)) {
    patchJson(tauriPath, (j) => {
      j.version = version;
    });
  }

  const outTs = path.join(root, "src", "content", "version.ts");
  fs.writeFileSync(
    outTs,
    `/** Auto-generated by scripts/sync-version.js — edit VERSION, not this file. */\n` +
      `export const GAME_VERSION = "${version}";\n` +
      `export const GAME_VERSION_LABEL = \`v${version}\`;\n`,
  );

  console.log(`Synced game version → ${version}`);
  return version;
}

if (require.main === module) {
  sync();
}

module.exports = { readVersion, sync };
